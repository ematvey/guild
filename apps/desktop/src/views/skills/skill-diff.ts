// Line diff for the skill publish guard: an LCS over lines produces
// added/removed/context rows the review step renders per changed file.
// Pure — no DOM, no server.

/** One diff row: "+" added, "-" removed, " " context. */
export interface DiffLine {
  type: "add" | "del" | "ctx";
  text: string;
}

/** Line-count guard for the LCS table: beyond this product the O(n·m)
 *  matrix would blow memory, so the diff degrades to replace-all. */
const LCS_CELL_BUDGET = 4_000_000;

/** Split into diff lines: "" is zero lines and a single trailing newline
 *  does not create an empty row ("a\n" is one line). */
function splitLines(text: string): string[] {
  if (text === "") return [];
  const lines = text.split("\n");
  if (lines.length > 1 && lines[lines.length - 1] === "") lines.pop();
  return lines;
}

/** LCS line diff of `oldText` → `newText` (split on "\n"). */
export function diffLines(oldText: string, newText: string): DiffLine[] {
  const a = splitLines(oldText);
  const b = splitLines(newText);
  const n = a.length;
  const m = b.length;
  if (n * m > LCS_CELL_BUDGET) {
    return [
      ...a.map((text): DiffLine => ({ type: "del", text })),
      ...b.map((text): DiffLine => ({ type: "add", text })),
    ];
  }
  // dp[i][j] = LCS length of a[i..] vs b[j..]
  const dp: Uint32Array[] = Array.from({ length: n + 1 }, () => new Uint32Array(m + 1));
  for (let i = n - 1; i >= 0; i--) {
    for (let j = m - 1; j >= 0; j--) {
      dp[i]![j] = a[i] === b[j] ? dp[i + 1]![j + 1]! + 1 : Math.max(dp[i + 1]![j]!, dp[i]![j + 1]!);
    }
  }
  const out: DiffLine[] = [];
  let i = 0;
  let j = 0;
  while (i < n && j < m) {
    if (a[i] === b[j]) {
      out.push({ type: "ctx", text: a[i]! });
      i++;
      j++;
    } else if (dp[i + 1]![j]! >= dp[i]![j + 1]!) {
      out.push({ type: "del", text: a[i]! });
      i++;
    } else {
      out.push({ type: "add", text: b[j]! });
      j++;
    }
  }
  while (i < n) out.push({ type: "del", text: a[i++]! });
  while (j < m) out.push({ type: "add", text: b[j++]! });
  return out;
}
